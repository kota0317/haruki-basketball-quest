'use strict';
const assert = require('node:assert/strict');
const { create } = require('./offline-queue.js');
const data = new Map();
const storage = {getItem:k => data.has(k) ? data.get(k) : null, setItem:(k,v) => data.set(k,v)};
const q = create(storage, 'sync');
const a = {id:'a',type:'task',value:{title:'英語'}};
const b = {id:'b',type:'completion',value:{xp:10}};
q.enqueue(a); q.enqueue(a); q.enqueue(b);
assert.equal(q.pending().length,2);
assert.throws(()=>q.enqueue({...a,value:{title:'別'}}),/reused/);
q.applyResults([{id:'a',result:{status:'applied'}},{id:'b',result:{status:'conflict',current:{revision:2}}}]);
assert.deepEqual(q.pending(),[]);
assert.equal(q.inspect().operations[0].status,'conflict');
assert.equal(create(storage,'sync').inspect().operations[0].server.revision,2);
assert.throws(()=>q.applyResults([{id:'b',result:{status:'applied'}},{id:'b',result:{status:'applied'}}]),/Invalid/);
assert.equal(q.inspect().operations.length,1);
const failing = create({getItem:()=>null,setItem:()=>{throw Error('quota')}},'x');
assert.throws(()=>failing.enqueue(a),/quota/);
data.set('bad','{');
assert.throws(()=>create(storage,'bad').enqueue(a));
assert.equal(data.get('bad'),'{');
console.log('PASS queue persistence, retry identity, conflict retention and storage failure');
